// ── Fuel Phase 1 migration, generated from fixtures/fuel-seed.json ──────────
//
//   node scripts/fuel-seed-sql.mjs          writes supabase/migrations/20260914_fuel_phase_1.sql
//   node scripts/fuel-seed-sql.mjs --check  exits 1 if the file on disk differs from what it would write
//
// The seed rows are Andrew's fortnight rotation as Blaine read it from the two
// Google Docs. Generating the SQL from the fixture means the migration and
// the fixture cannot disagree; the fuel-solve check runs --check.
//
// Tables and RLS ship in the SAME migration (rls_hardening lesson). The one
// write path for check state is a database function so that the row stays
// authoritative — see src/lib/fuel/ticks.ts.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
export const MIGRATION = join(ROOT, 'supabase', 'migrations', '20260914_fuel_phase_1.sql')
const seed = JSON.parse(readFileSync(join(ROOT, 'fixtures', 'fuel-seed.json'), 'utf8'))

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const n = (v) => (v == null ? 'NULL' : String(v))

const sectionOrder = seed.store_section_order

export function render() {
  const rows = seed.fuel_meals.map((m) => `  (${[
    q(m.slug), q(m.name), q(m.protein_cut), q(m.spice_profile), q(m.format),
    n(m.active_cook_minutes), n(m.total_minutes), n(m.servings), n(m.protein_g_per_person),
    n(m.perishable_within_days), m.rotation_note ? q(m.rotation_note) : 'NULL', j(m.ingredients),
  ].join(', ')})`).join(',\n')

  return `-- ============================================================
-- Fuel Phase 1 (FOR-177) — 2026-09-14
-- GENERATED by scripts/fuel-seed-sql.mjs from fixtures/fuel-seed.json.
-- Do not edit by hand; edit the fixture and regenerate.
--
-- Four tables, RLS in the same migration, and the ONE write path for
-- check state. Seeded with Andrew's fortnight rotation: ${seed.fuel_meals.length} meals,
-- one complete cycle. Protein quantities are sourced; every side quantity
-- is marked "inferred": true in the ingredient JSON and must be presented
-- as an estimate until Andrew corrects it.
-- ============================================================

-- ── fuel_meals: the curated library, read-only to users ──────────────────
CREATE TABLE IF NOT EXISTS public.fuel_meals (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug                   text UNIQUE NOT NULL,
  name                   text NOT NULL,
  protein_cut            text NOT NULL,
  spice_profile          text NOT NULL,
  format                 text NOT NULL,
  active_cook_minutes    int  NOT NULL,
  total_minutes          int,
  servings               int  NOT NULL DEFAULT 2,   -- cooked at, not eaten by: 3 buys a leftover night
  protein_g_per_person   int,
  perishable_within_days int,
  rotation_note          text,
  ingredients            jsonb NOT NULL DEFAULT '[]'::jsonb, -- [{item, qty_per_person, unit, store_section, inferred}]
  active                 boolean NOT NULL DEFAULT true,
  created_at             timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.fuel_meals ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "fuel_meals: authenticated read" ON public.fuel_meals;
CREATE POLICY "fuel_meals: authenticated read" ON public.fuel_meals
  FOR SELECT TO authenticated USING (true);
-- No INSERT / UPDATE / DELETE policy: users never write the library.

-- ── fuel_household: one row per user, owner-only ─────────────────────────
CREATE TABLE IF NOT EXISTS public.fuel_household (
  user_id             uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  people_count        int NOT NULL DEFAULT 2 CHECK (people_count BETWEEN 1 AND 12),
  nights_per_week     int NOT NULL DEFAULT 4 CHECK (nights_per_week BETWEEN 1 AND 7),
  cook_cap_minutes    int NOT NULL DEFAULT 30 CHECK (cook_cap_minutes BETWEEN 5 AND 180),
  shop_cadence_days   int NOT NULL DEFAULT 14 CHECK (shop_cadence_days IN (7, 14)),
  prep_diversion_pct  int NOT NULL DEFAULT 0 CHECK (prep_diversion_pct BETWEEN 0 AND 90), -- L2, first-class
  dietary_rules       jsonb NOT NULL DEFAULT '{}'::jsonb,
  inventory           jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{item, qty, unit}]
  store_section_order jsonb NOT NULL DEFAULT ${j(sectionOrder)},
  updated_at          timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.fuel_household ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "fuel_household: owner" ON public.fuel_household;
CREATE POLICY "fuel_household: owner" ON public.fuel_household
  FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- ── fuel_plans: versioned picks, old versions kept (L6, L7) ──────────────
CREATE TABLE IF NOT EXISTS public.fuel_plans (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id        uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  week_start     date NOT NULL,
  version        int  NOT NULL CHECK (version >= 1),
  meal_ids       jsonb NOT NULL,   -- [{slug, week, servings}]
  rules_snapshot jsonb NOT NULL,   -- the household as it was when this version was solved
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, week_start, version)
);
ALTER TABLE public.fuel_plans ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "fuel_plans: owner" ON public.fuel_plans;
CREATE POLICY "fuel_plans: owner" ON public.fuel_plans
  FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- ── fuel_lists: the checklist, one row per plan version ──────────────────
CREATE TABLE IF NOT EXISTS public.fuel_lists (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_id    uuid NOT NULL REFERENCES public.fuel_plans(id) ON DELETE CASCADE,
  user_id    uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  version    int  NOT NULL CHECK (version >= 1),
  items      jsonb NOT NULL,   -- ListItem[] from src/lib/fuel/solve.ts, with per-item checked
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (plan_id, version)
);
ALTER TABLE public.fuel_lists ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "fuel_lists: owner" ON public.fuel_lists;
CREATE POLICY "fuel_lists: owner" ON public.fuel_lists
  FOR ALL TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE INDEX IF NOT EXISTS fuel_lists_user_version ON public.fuel_lists (user_id, version DESC);
CREATE INDEX IF NOT EXISTS fuel_plans_user_version ON public.fuel_plans (user_id, week_start, version DESC);

-- ── The one write path for check state — the ROW is authoritative ────────
-- One item, one atomic update, returning the whole row's items so the
-- client replaces its render with what the row now says. SECURITY INVOKER:
-- RLS applies, and the WHERE repeats the owner test anyway.
CREATE OR REPLACE FUNCTION public.fuel_set_item_checked(p_list_id uuid, p_key text, p_checked boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  new_items jsonb;
BEGIN
  UPDATE public.fuel_lists
  SET items = (
        SELECT COALESCE(
          jsonb_agg(
            CASE WHEN elem->>'key' = p_key THEN jsonb_set(elem, '{checked}', to_jsonb(p_checked), true) ELSE elem END
            ORDER BY ord
          ), '[]'::jsonb)
        FROM jsonb_array_elements(items) WITH ORDINALITY AS t(elem, ord)
      ),
      updated_at = now()
  WHERE id = p_list_id AND user_id = auth.uid()
  RETURNING items INTO new_items;
  IF new_items IS NULL THEN
    RAISE EXCEPTION 'fuel list % is not yours or does not exist', p_list_id USING ERRCODE = '42501';
  END IF;
  RETURN new_items;
END
$$;
REVOKE EXECUTE ON FUNCTION public.fuel_set_item_checked(uuid, text, boolean) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.fuel_set_item_checked(uuid, text, boolean) TO authenticated;

-- ── A new version is ONE transaction: plan row + list row together ───────
-- The version number is chosen here under the unique constraint, so two
-- clients cannot race for it and a failed list insert cannot leave an
-- orphan plan holding a number. SECURITY INVOKER: RLS applies to both
-- inserts, and user_id is auth.uid() by construction.
CREATE OR REPLACE FUNCTION public.fuel_create_version(p_week_start date, p_meal_ids jsonb, p_rules_snapshot jsonb, p_items jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  v_version int;
  v_plan_id uuid;
  v_list_id uuid;
  v_updated timestamptz;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not signed in' USING ERRCODE = '42501';
  END IF;
  SELECT COALESCE(MAX(version), 0) + 1 INTO v_version
    FROM public.fuel_plans WHERE user_id = auth.uid() AND week_start = p_week_start;
  INSERT INTO public.fuel_plans (user_id, week_start, version, meal_ids, rules_snapshot)
    VALUES (auth.uid(), p_week_start, v_version, p_meal_ids, p_rules_snapshot)
    RETURNING id INTO v_plan_id;
  INSERT INTO public.fuel_lists (plan_id, user_id, version, items)
    VALUES (v_plan_id, auth.uid(), v_version, p_items)
    RETURNING id, updated_at INTO v_list_id, v_updated;
  RETURN jsonb_build_object('plan_id', v_plan_id, 'list_id', v_list_id, 'version', v_version, 'updated_at', v_updated);
END
$$;
REVOKE EXECUTE ON FUNCTION public.fuel_create_version(date, jsonb, jsonb, jsonb) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.fuel_create_version(date, jsonb, jsonb, jsonb) TO authenticated;

-- ── Seed: Andrew's fortnight rotation (${seed.fuel_meals.length} meals), from the fixture ───
INSERT INTO public.fuel_meals
  (slug, name, protein_cut, spice_profile, format, active_cook_minutes, total_minutes, servings, protein_g_per_person, perishable_within_days, rotation_note, ingredients)
VALUES
${rows}
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name, protein_cut = EXCLUDED.protein_cut, spice_profile = EXCLUDED.spice_profile,
  format = EXCLUDED.format, active_cook_minutes = EXCLUDED.active_cook_minutes, total_minutes = EXCLUDED.total_minutes,
  servings = EXCLUDED.servings, protein_g_per_person = EXCLUDED.protein_g_per_person,
  perishable_within_days = EXCLUDED.perishable_within_days, rotation_note = EXCLUDED.rotation_note,
  ingredients = EXCLUDED.ingredients;
`
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === join(process.cwd(), process.argv[1].replace(process.cwd(), '').replace(/^[\\/]/, ''))
  || process.argv[1]?.endsWith('fuel-seed-sql.mjs')
if (isMain) {
  const out = render()
  if (process.argv.includes('--check')) {
    const onDisk = readFileSync(MIGRATION, 'utf8').replace(/\r\n/g, '\n')
    if (onDisk !== out) { console.error('migration differs from the fixture — run: node scripts/fuel-seed-sql.mjs'); process.exit(1) }
    console.log('migration matches the fixture')
  } else {
    writeFileSync(MIGRATION, out)
    console.log('wrote', MIGRATION, `(${seed.fuel_meals.length} meals)`)
  }
}
