// ── Imported: the weightlifting libraries (FOR-350) ──────────────────────────
// Every exercise Catalyst Athletics and trainingweightlifting.com list, read
// 2026-11-15/16, that the core library did not already hold. Named the way the
// sources name them; where the two sites name one movement differently, the
// second name is an `aka` on the first. The raw source lists live in
// scripts/checks/exercise-sources/oly.json, and the exercise-library check
// proves every name there resolves to exactly one entry here or in the core.
//
// Categories: pulls, deadlifts, shrugs, lift-offs and high pulls are oly_pull;
// RDLs, straight-leg deadlifts and good mornings are hinge; plain squats are
// squat; strict presses are push_v; split squats are lunge. Snatch-grip
// overhead work is snatch; clean and jerk work is clean_jerk.
//
// `impact` marks a drill that lands or jumps (jump to split, rebound jerk,
// jumping pulls). Platform Dad never prescribes one; the flag lets a knee-safe
// program keep them out of its swaps.

